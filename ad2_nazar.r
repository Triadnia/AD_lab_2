# ДОПОМІЖНІ ФУНКЦІЇ ДЛЯ ТЕСТІВ (Асимптотичний ДІ та Тест Волда)
# =========================================================================
format_ci <- function(ci_vector) {
  sprintf("[%10.2f; %10.2f]", ci_vector[1], ci_vector[2])
}

asymptotic_ci_mean <- function(x) {
  n <- length(x)
  se <- sd(x) / sqrt(n)
  margin <- qnorm(0.975) * se
  c(mean(x) - margin, mean(x) + margin)
}

wald_test_means <- function(x1, x2) {
  mean_diff <- mean(x1) - mean(x2)
  se_diff <- sqrt((var(x1)/length(x1)) + (var(x2)/length(x2)))
  w_stat <- mean_diff / se_diff
  p_val <- 2 * (1 - pnorm(abs(w_stat)))
  return(c(W = w_stat, p_value = p_val))
}


