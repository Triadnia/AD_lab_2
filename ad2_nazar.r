# =========================================================================
#
# Оскільки одночасно тестуємо 4 гіпотези, виникає проблема множинного тестування:
# ймовірність хибно відкинути хоча б одну H₀ зростає зі збільшенням кількості тестів.
# Метод Бенджаміні-Хохберга (BH) контролює False Discovery Rate (FDR) —
# очікувану частку хибних відхилень серед усіх відхилень — на рівні 5%.
# BH є потужнішим (менш консервативним) за поправку Бонфероні і підходить
# для незалежних або позитивно скорельованих тестів (що виконується тут,
# оскільки всі гіпотези стосуються одного датасету).
# =========================================================================

