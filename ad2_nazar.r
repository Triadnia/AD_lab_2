# ГІПОТЕЗА 1: РІЗНИЦЯ СЕРЕДНІХ (ВСІ ДАНІ З КАТАСТРОФАМИ)
# =========================================================================
#
# --- ОПИС ВИБІРОК ---
# g1_sev: загальна вартість страхових виплат для страхувальників-молоді (18–25 р.),
#         які водять СТАРІ (VehAge >= 11) та ПОТУЖНІ (VehPower >= 9) автомобілі.
# g2_sev: аналогічна вибірка для ДОРОСЛИХ (26–59 р.) з тими ж характеристиками авто.
# Обидві вибірки — незалежні підмножини спостережень з df_claims
# (лише ті, хто мав хоча б один страховий випадок).
#
# --- СТАТИСТИКА ТА ЇЇ АСИМПТОТИЧНИЙ РОЗПОДІЛ ---
# Статистика: вибіркове середнє  x̄ = (1/n) * Σ xᵢ
#
# Чому це ГРУПА 1? Три критерії, які потрібно перевірити одночасно:
#
#   [1] ЧИ МАЄ СТАТИСТИКА АСИМПТОТИЧНО НОРМАЛЬНИЙ РОЗПОДІЛ?
#       Так — це безпосередньо випливає з Центральної Граничної Теореми (ЦГТ).
#       ЦГТ застосовна, якщо виконані умови:
#         (а) спостереження xᵢ — незалежні (різні страхові поліси, різні водії ✓)
#         (б) спостереження однаково розподілені (i.i.d.) в межах кожної групи ✓
#         (в) існують скінченні E[X] = μ та Var(X) = σ² < ∞
#             (страхові виплати обмежені знизу нулем; важкий хвіст є, але
#              для фінансових даних з конечними моментами ЦГТ все одно діє ✓)
#         (г) розмір вибірки достатньо великий (n >> 30, що тут виконується ✓)
#       За ЦГТ: √n * (x̄ - μ) → N(0, σ²),  тобто  x̄ ~асимпт. N(μ, σ²/n)
#
#   [2] ЧИ ВІДОМА ФОРМУЛА АСИМПТОТИЧНОЇ ДИСПЕРСІЇ?
#       Так — з тієї ж ЦГТ: Var(x̄) = σ²/n.
#       Формула є явною і не залежить від невідомих величин, крім σ².
#
#   [3] ЧИ ЛЕГКО ОЦІНИТИ ЦЮ ДИСПЕРСІЮ?
#       Так — σ² замінюється вибірковою дисперсією s² = (1/(n-1)) * Σ(xᵢ - x̄)²,
#       яка є незміщеною і консистентною оцінкою σ².
#       Оцінка дисперсії x̄: s²/n = var(x)/n — обчислюється аналітично в один рядок,
#       без числових методів (бутстрепу, ядрових оцінок тощо).
#
#   Оскільки всі три умови виконані → статистика належить до ГРУПИ 1.
#
# --- ФОРМУЛА ДИСПЕРСІЇ ---
# Асимптотична дисперсія вибіркового середнього: Var(x̄) = σ²/n
# Оцінка (plug-in): s²/n, де s² = (1/(n-1)) * Σ(xᵢ - x̄)²  — вибіркова дисперсія.
#
# --- ДОВІРЧИЙ ІНТЕРВАЛ ---
# ДІ рівня 95%: x̄ ± z_{0.975} * (s / √n),  де z_{0.975} ≈ 1.96
#
# --- ТЕСТ ВОЛДА ДЛЯ РІЗНИЦІ СЕРЕДНІХ ---
# H₀: μ₁ = μ₂  (середні вартості збитків однакові)
# H₁: μ₁ ≠ μ₂  (двостороння альтернатива: не маємо апріорних підстав
#                стверджувати, в який бік різниця більша)
# Тестова статистика Волда:
#   W = (x̄₁ - x̄₂) / √(s₁²/n₁ + s₂²/n₂)
# За H₀: W → N(0,1) асимптотично.
# p-значення (двостороннє): p = 2 * (1 - Φ(|W|))
# =========================================================================

g1_sev <- df_claims %>% filter(AgeGroup == "Youth", CarAgeGroup == "Old", PowerGroup == "High") %>% pull(Total_Claim_Amount)
g2_sev <- df_claims %>% filter(AgeGroup == "Adults", CarAgeGroup == "Old", PowerGroup == "High") %>% pull(Total_Claim_Amount)

ci_g1_mean <- asymptotic_ci_mean(g1_sev)
ci_g2_mean <- asymptotic_ci_mean(g2_sev)
test_h1 <- wald_test_means(g1_sev, g2_sev)


# =========================================================================
# ГІПОТЕЗА 2: РІЗНИЦЯ СЕРЕДНІХ (БЕЗ ТОП-0.5% КАТАСТРОФ)
# =========================================================================
#
# --- МОТИВАЦІЯ ---
# Розподіл страхових виплат є сильно правосторонньо скошеним: невелика кількість
# катастрофічних подій може суттєво завищувати середнє і спотворювати порівняння.
# Відсікання top-0.5% дозволяє перевірити гіпотезу 1 на «типових» збитках,
# без впливу екстремальних викидів.
#
# --- ОПИС ВИБІРОК ---
# g1_sev_typ / g2_sev_typ: ті ж групи, що в Гіпотезі 1, але з умовою
# Total_Claim_Amount <= quantile(df_claims$Total_Claim_Amount, 0.995).
# Вибірки залишаються незалежними.
#
# --- СТАТИСТИКА ТА ЇЇ АСИМПТОТИЧНИЙ РОЗПОДІЛ ---
# Статистика: вибіркове середнє усіченої вибірки  x̄_усіч = (1/n_усіч) * Σ xᵢ · 𝟙[xᵢ ≤ q_{0.995}]
#
# Чому це ГРУПА 1? Та сама логіка, що в Гіпотезі 1, з одним уточненням:
#
#   [1] ЧИ МАЄ СТАТИСТИКА АСИМПТОТИЧНО НОРМАЛЬНИЙ РОЗПОДІЛ?
#       Так — ЦГТ застосовна і до усіченої підвибірки.
#       Усічення (відсікання top-0.5%) — це детермінований фільтр за порогом q_{0.995},
#       що не залежить від конкретних значень у вибірці (поріг вираховується глобально
#       по df_claims, а не окремо по групі). Після відсікання залишкові спостереження
#       є i.i.d. з усіченого розподілу, тому ЦГТ застосовується без змін:
#         √n_усіч * (x̄_усіч - μ_усіч) → N(0, σ²_усіч)
#       де μ_усіч = E[X | X ≤ q_{0.995}],  σ²_усіч = Var(X | X ≤ q_{0.995}).
#
#   [2] ЧИ ВІДОМА ФОРМУЛА АСИМПТОТИЧНОЇ ДИСПЕРСІЇ?
#       Так — Var(x̄_усіч) = σ²_усіч / n_усіч.
#       Формула ідентична за структурою до Гіпотези 1, тільки параметри
#       стосуються усіченого (а не повного) розподілу.
#
#   [3] ЧИ ЛЕГКО ОЦІНИТИ ЦЮ ДИСПЕРСІЮ?
#       Так — σ²_усіч оцінюється вибірковою дисперсією усіченої підвибірки
#       s²_усіч = var(g1_sev_typ), яка є консистентною оцінкою.
#       Жодних числових методів не потрібно — оцінка аналітична.
#
#   Оскільки всі три умови виконані → статистика належить до ГРУПИ 1.
#
# --- ФОРМУЛА ДИСПЕРСІЇ ---
# Var(x̄_усіч) = σ²_усіч / n_усіч
# Оцінка (plug-in): s²_усіч / n_усіч = var(усіченої вибірки) / її розмір.
#
# --- ДОВІРЧИЙ ІНТЕРВАЛ ---
# ДІ рівня 95%: x̄_усіч ± z_{0.975} * (s_усіч / √n_усіч)
#
# --- ТЕСТ ВОЛДА ДЛЯ РІЗНИЦІ СЕРЕДНІХ ---
# H₀: μ₁_усіч = μ₂_усіч
# H₁: μ₁_усіч ≠ μ₂_усіч  (двостороння; перевіряємо, чи зберігається
#                           різниця навіть після виключення катастроф)
# W = (x̄₁_усіч - x̄₂_усіч) / √(s₁²_усіч/n₁ + s₂²_усіч/n₂)
# p = 2 * (1 - Φ(|W|))
# =========================================================================

threshold_995 <- quantile(df_claims$Total_Claim_Amount, 0.995)

g1_sev_typ <- df_claims %>% filter(AgeGroup == "Youth", CarAgeGroup == "Old", PowerGroup == "High", Total_Claim_Amount <= threshold_995) %>% pull(Total_Claim_Amount)
g2_sev_typ <- df_claims %>% filter(AgeGroup == "Adults", CarAgeGroup == "Old", PowerGroup == "High", Total_Claim_Amount <= threshold_995) %>% pull(Total_Claim_Amount)

ci_g1_typ_mean <- asymptotic_ci_mean(g1_sev_typ)
ci_g2_typ_mean <- asymptotic_ci_mean(g2_sev_typ)
test_h2 <- wald_test_means(g1_sev_typ, g2_sev_typ)


# =========================================================================
# ГІПОТЕЗА 3: РІЗНИЦЯ МЕДІАН (БУТСТРЕП)
# =========================================================================
#
# --- ОПИС ВИБІРОК ---
# g3_sev: вартість збитків для ПЕНСІОНЕРІВ (60+) на ПОТУЖНИХ авто (VehPower >= 9).
#         Гіпотеза «небезпечного дідуся»: літні водії на потужних авто можуть
#         генерувати більші збитки через сповільнену реакцію.
# g4_sev: вартість збитків для ДОРОСЛИХ (26–59) на СЛАБКИХ авто (VehPower <= 5)
#         в урбанізованих районах (Area ∈ {E, F} — великі міста).
#         Міські водії на малолітражках як «безпечна» контрольна група.
# Обидві вибірки незалежні.
#
# --- СТАТИСТИКА ТА ЇЇ АСИМПТОТИЧНИЙ РОЗПОДІЛ ---
# Статистика: вибіркова медіана  Q_{0.5} — значення, яке ділить вибірку навпіл.
#
# Чому це ГРУПА 2? Перевіряємо ті самі три критерії:
#
#   [1] ЧИ МАЄ СТАТИСТИКА АСИМПТОТИЧНО НОРМАЛЬНИЙ РОЗПОДІЛ?
#       Так — медіана теж має асимптотично нормальний розподіл за теоремою
#       про асимптотичний розподіл квантилів (Bahadur, 1966):
#         √n * (Q̂_{0.5} - Q_{0.5}) → N(0, 1/(4·[f(Q_{0.5})]²))
#       де f — густина розподілу генеральної сукупності в точці медіани Q_{0.5}.
#       Умова: f має бути неперервною і додатною в точці медіани (для страхових
#       виплат із ненульовою ймовірністю ненульових збитків — виконується ✓).
#
#   [2] ЧИ ВІДОМА ФОРМУЛА АСИМПТОТИЧНОЇ ДИСПЕРСІЇ?
#       Так — Var(Q̂_{0.5}) = 1 / (4·n·[f(Q_{0.5})]²).
#       Формула є явною, але залежить від f(Q_{0.5}) — значення НЕВІДОМОЇ густини
#       розподілу в точці медіани.
#
#   [3] ЧИ ЛЕГКО ОЦІНИТИ ЦЮ ДИСПЕРСІЮ?
#       НІ — і ось чому це ГРУПА 2, а не ГРУПА 1:
#       Щоб оцінити f(Q_{0.5}), потрібна ядрова оцінка густини:
#         f̂(Q̂_{0.5}) = (1/(n·h)) · Σ K((xᵢ - Q̂_{0.5})/h)
#       де K — ядро (наприклад, гауссівське), h — ширина вікна (bandwidth).
#       Ця оцінка є СКЛАДНОЮ з двох причин:
#         (а) вибір h суттєво впливає на результат і не має однозначного рішення
#             для важкохвостих (скошених) розподілів страхових виплат;
#         (б) для малих вибірок (що може бути тут для сегменту пенсіонерів)
#             ядрова оцінка є ненадійною.
#       Тому замість аналітичної оцінки дисперсії використовуємо БУТСТРЕП.
#
# --- МОТИВАЦІЯ БУТСТРЕПУ ---
# Бутстреп уникає оцінки f(Q_{0.5}) взагалі: він безпосередньо відтворює
# вибірковий розподіл медіани шляхом повторної вибірки з поверненням.
# Кількість бутстреп-вибірок: R = 1000 (стандарт для percentile CI;
# для studentized CI рекомендується R ≥ 2000, але тут використовується простіший метод).
#
# --- ДОВІРЧИЙ ІНТЕРВАЛ ---
# Percentile bootstrap CI: [Q_{0.025}(медіана*), Q_{0.975}(медіана*)],
# де медіана* — медіана кожної бутстреп-вибірки.
#
# --- ТЕСТ ВОЛДА ДЛЯ РІЗНИЦІ МЕДІАН (БУТСТРЕП SE) ---
# H₀: Q_{0.5,1} = Q_{0.5,2}
# H₁: Q_{0.5,1} ≠ Q_{0.5,2}  (двостороння; не знаємо напевне, яка група матиме
#                               більшу медіану — перевіряємо сам факт різниці)
# Оскільки аналітичну SE дисперсії ми не оцінюємо, SE різниці медіан
# береться з бутстреп-розподілів (за незалежністю вибірок дисперсії підсумовуються):
#   SE_diff = √(Var(медіана₁*) + Var(медіана₂*))
# де Var(медіана*) = емпірична дисперсія R бутстреп-значень медіани.
# Тестова статистика:
#   W = (Q̂_{0.5,1} - Q̂_{0.5,2}) / SE_diff
# За H₀: W → N(0,1) асимптотично (нормальність самих медіан + велика кількість
# бутстреп-ітерацій забезпечує надійну оцінку SE).
# p = 2 * (1 - Φ(|W|))
# =========================================================================

g3_sev <- df_claims %>% filter(AgeGroup == "Seniors", PowerGroup == "High") %>% pull(Total_Claim_Amount)
g4_sev <- df_claims %>% filter(AgeGroup == "Adults", PowerGroup == "Low", Area %in% c("E", "F")) %>% pull(Total_Claim_Amount)

median_fun <- function(data, indices) { return(median(data[indices])) }

set.seed(42)
boot_g3 <- boot(data = g3_sev, statistic = median_fun, R = 1000)
boot_g4 <- boot(data = g4_sev, statistic = median_fun, R = 1000)

ci_g3_median_vals <- boot.ci(boot_g3, type = "perc")$percent[4:5]
ci_g4_median_vals <- boot.ci(boot_g4, type = "perc")$percent[4:5]

wald_test_medians <- function(boot1, boot2) {
  med_diff <- boot1$t0 - boot2$t0
  se_diff <- sqrt(var(boot1$t) + var(boot2$t))
  w_stat <- med_diff / se_diff
  p_val <- 2 * (1 - pnorm(abs(w_stat)))
  return(c(W = w_stat, p_value = p_val))
}
test_h3 <- wald_test_medians(boot_g3, boot_g4)


# =========================================================================
# ГІПОТЕЗА 4: РІЗНИЦЯ ЧАСТОК (ПРОПОРЦІЙ)
# =========================================================================
#
# --- ОПИС ВИБІРОК ---
# g5_freq: бінарна змінна HasClaim ∈ {0,1} для МОЛОДІ (18–25)
#          на НОВИХ (VehAge <= 3) та СЛАБКИХ (VehPower <= 5) авто.
# g6_freq: те саме для ДОРОСЛИХ (26–59) з тими ж характеристиками авто.
# «Парадокс нових малолітражок»: молодь може вибирати ці авто як «безпечні»,
# проте частота ДТП у них може все одно бути вищою через недосвідченість.
# Обидві вибірки незалежні (різні страхові поліси).
#
# --- СТАТИСТИКА ТА ЇЇ АСИМПТОТИЧНИЙ РОЗПОДІЛ ---
# Статистика: вибіркова частка  p̂ = (1/n) * Σ HasClaimᵢ
#
# Чому це ГРУПА 1? Ключове спостереження: частка є СЕРЕДНІМ бінарної змінної.
#
#   [1] ЧИ МАЄ СТАТИСТИКА АСИМПТОТИЧНО НОРМАЛЬНИЙ РОЗПОДІЛ?
#       Так — HasClaimᵢ ∈ {0,1} є i.i.d. Бернуллі(p) з:
#         E[HasClaim] = p,    Var(HasClaim) = p*(1-p)
#       Обидва моменти скінченні для будь-якого p ∈ (0,1).
#       Тому ЦГТ застосовується так само, як і для будь-якого середнього:
#         √n * (p̂ - p) → N(0, p*(1-p))
#       Отже: p̂ ~асимпт. N(p, p*(1-p)/n)
#
#   [2] ЧИ ВІДОМА ФОРМУЛА АСИМПТОТИЧНОЇ ДИСПЕРСІЇ?
#       Так — Var(p̂) = p*(1-p)/n.
#       Ця формула є точним наслідком розподілу Бернуллі і не потребує
#       ніяких додаткових теорем, крім ЦГТ.
#
#   [3] ЧИ ЛЕГКО ОЦІНИТИ ЦЮ ДИСПЕРСІЮ?
#       Так — єдиний невідомий параметр p замінюється plug-in оцінкою p̂:
#         Var̂(p̂) = p̂*(1-p̂)/n
#       Ця оцінка є консистентною (p̂ → p за законом великих чисел),
#       обчислюється аналітично, без числових методів.
#
#   Оскільки всі три умови виконані → статистика належить до ГРУПИ 1.
#   (Порівняно з Г3: для частки ми ЗНАЄМО форму дисперсії через розподіл Бернуллі;
#    для медіани дисперсія залежить від невідомої густини f — ось принципова різниця.)
#
# --- ФОРМУЛА ДИСПЕРСІЇ ---
# Теоретична: Var(p̂) = p*(1-p)/n
# Оцінка (plug-in): p̂*(1-p̂)/n  (підставляємо p̂ замість невідомого p)
# Зв'язок з var(x)/n: для бінарного вектора x, var(x) = p̂*(1-p̂)·n/(n-1) ≈ p̂*(1-p̂)
# при великих n — саме тому wald_test_means коректно обчислює SE для часток.
#
# --- ДОВІРЧИЙ ІНТЕРВАЛ (Вальда для пропорції) ---
# ДІ рівня 95%: p̂ ± z_{0.975} * √(p̂*(1-p̂)/n)
#
# --- ТЕСТ ВОЛДА ДЛЯ РІЗНИЦІ ПРОПОРЦІЙ ---
# H₀: p₁ = p₂  (частоти ДТП однакові для молоді та дорослих)
# H₁: p₁ ≠ p₂  (двостороння; хоча інтуїтивно очікуємо p₁ > p₂,
#                обираємо двосторонню для коректності множинного тестування)
# SE різниці: √(p̂₁*(1-p̂₁)/n₁ + p̂₂*(1-p̂₂)/n₂)
# Тестова статистика:
#   W = (p̂₁ - p̂₂) / SE_diff
# (Реалізовано через wald_test_means, оскільки для бінарної змінної
#  різниця середніх = різниця пропорцій, а var(x)/n = p̂*(1-p̂)/n)
# p = 2 * (1 - Φ(|W|))
# =========================================================================

g5_freq <- df %>% filter(AgeGroup == "Youth", CarAgeGroup == "New", PowerGroup == "Low") %>% pull(HasClaim)
g6_freq <- df %>% filter(AgeGroup == "Adults", CarAgeGroup == "New", PowerGroup == "Low") %>% pull(HasClaim)

asymptotic_ci_prop <- function(x) {
  n <- length(x)
  p <- mean(x)
  se <- sqrt(p * (1 - p) / n)
  margin <- qnorm(0.975) * se
  c(p - margin, p + margin)
}

ci_g5_prop <- asymptotic_ci_prop(g5_freq)
ci_g6_prop <- asymptotic_ci_prop(g6_freq)
test_h4 <- wald_test_means(g5_freq, g6_freq)


